def prepare_data():
    if os.path.exists(DATA_PATH):
        return

    os.makedirs(
        DATA_PATH, exist_ok=True
    )
    image_files = [file for file in os.listdir(ORIGINAL_DATA_PATH) if 'image' in file and file.endswith('.png')]
    for cv_subject in CV_SUBJECTS:
        os.makedirs(
            os.path.join(DATA_PATH, cv_subject), exist_ok=True
        )
        cv_subject_images = [file for file in image_files if cv_subject in file]
        # Move all images to DATA_PATH
        for image in cv_subject_images:
            shutil.copy(os.path.join(ORIGINAL_DATA_PATH, image), os.path.join(DATA_PATH, cv_subject, image))
    
