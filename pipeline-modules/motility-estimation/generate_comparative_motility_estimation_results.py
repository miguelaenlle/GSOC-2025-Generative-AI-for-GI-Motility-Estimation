            # Path where the data is 
            cv_subject_data_path = os.path.join(DATA_PATH, cv_subject)

            # Path leading to the export directory for the cv_subject
            cv_subject_export_path = os.path.join(model_path, cv_subject)
            if os.path.exists(cv_subject_export_path) and not SKIP_SYNTHESIS:
                shutil.rmtree(cv_subject_export_path)
            os.makedirs(cv_subject_export_path, exist_ok=True)
            
            model_cv_subject_weights_path = model_data['weights'].get(cv_subject, None)
            if not model_cv_subject_weights_path:
                print(f"No model weights found for {cv_subject} with model {model_data['name']}, skipping.")
                continue

            model = smp.Unet(
                encoder_name='efficientnet-b1',
                encoder_weights="imagenet",
                in_channels=1,
                classes=1,
                activation=None,
            )
            model = model.to('cuda')
            if os.path.exists(model_cv_subject_weights_path):
                model.load_state_dict(torch.load(model_cv_subject_weights_path, map_location='cuda', weights_only=False))
                print(f"Model weights loaded from {model_cv_subject_weights_path}")
            else:
                print(f"Model weights not found at {model_cv_subject_weights_path}, skipping.")
                continue

            if not SKIP_SYNTHESIS:
                model.eval()
                normalize = transforms.Normalize(mean=[0.5], std=[0.5])
                for file in tqdm(os.listdir(cv_subject_data_path)):
                    if 'image' in file:
                        image_path = os.path.join(cv_subject_data_path, file)
                        image = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
                        if image is None:
                            print(f"Error reading image at {image_path}. Skipping this file.")
                            continue
                        
                        # Convert image to torch tensor
                        image = torch.tensor(image, dtype=torch.float32)  # Convert to float32
                        image = image.unsqueeze(0).unsqueeze(0).to('cuda')  # Add batch dimension and move to GPU

                        # 0-1 normalize the image
                        image = image / 255.0  # Normalize to [0, 1]

                        with torch.no_grad():
                            mask = model(normalize(image))

                        mask = mask.squeeze().cpu()  # Remove batch dimension and move back to CPU

                        # Scale mask to 0-1 range
                        mask = (torch.sigmoid(mask) > 0.5).cpu().numpy()
                        mask = (mask * 255).astype('uint8')

                        mask_path = os.path.join(cv_subject_export_path, file.replace('image', 'mask'))
                        
                        # Save the mask
                        cv2.imwrite(mask_path, mask)

            # Run the 3D reconstruction script
