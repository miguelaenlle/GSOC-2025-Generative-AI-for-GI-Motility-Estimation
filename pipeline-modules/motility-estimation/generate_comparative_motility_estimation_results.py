            # Run motility estimation
            cmd = [
                "matlab",            # or full path to matlab executable
                "-batch", f"run('{MOTILITY_ESTIMATION_M}')"
            ]
            proc = subprocess.run(cmd, capture_output=True, text=True)
            if proc.returncode != 0:
                print("MATLAB error:", proc.stderr, file=sys.stderr)
            else:
                print("MATLAB output:\n", proc.stdout)

            # comma-separated list of numbers
            cross_section_data = pd.read_csv(CROSS_SECTIONAL_AREAS_FILE, header=None)

